#!/usr/bin/env node
/**
 * One-time asset-generation script (run manually, not at build/runtime).
 *
 * Sources every real brand logo used in the Skills "periodic table" and the
 * Achievements gallery from two offline-safe places:
 *
 *   1. `simple-icons` (npm, CC0) — single-path, single-color brand marks.
 *   2. A handful of devicon SVGs (MIT) that simple-icons no longer ships
 *      (Microsoft Azure, AWS, C#) after their 2023 trademark-related
 *      removals. Those files were fetched once into scripts/devicon-cache/
 *      and are committed there so this script never needs network access.
 *
 * Output:
 *   - public/logos/<slug>.svg            (static, downloadable, citable)
 *   - public/logos/LICENSE-simple-icons.md
 *   - public/logos/LICENSE-devicon.txt
 *   - src/lib/logos.generated.ts         (inline React-ready path/markup data)
 *
 * Run with: node scripts/generate-logos.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";
import * as simpleIcons from "simple-icons";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const logosDir = path.join(root, "public", "logos");
const devCacheDir = path.join(__dirname, "devicon-cache");

mkdirSync(logosDir, { recursive: true });

// slug -> simple-icons export key
const SIMPLE_ICON_SLUGS = {
  python: "siPython",
  javascript: "siJavascript",
  html5: "siHtml5",
  tensorflow: "siTensorflow",
  ollama: "siOllama",
  kubernetes: "siKubernetes",
  git: "siGit",
  dotnet: "siDotnet",
  django: "siDjango",
  pandas: "siPandas",
  numpy: "siNumpy",
  mysql: "siMysql",
  jupyter: "siJupyter",
  nvidia: "siNvidia",
  ieee: "siIeee",
  arxiv: "siArxiv",
};

// slug -> cached devicon file (multi-path / gradient, copied verbatim)
const DEVICON_SLUGS = {
  azure: "azure_azure-original.svg",
  aws: "amazonwebservices_amazonwebservices-original-wordmark.svg",
  csharp: "csharp_csharp-original.svg",
};

const brandEntries = {};

for (const [slug, key] of Object.entries(SIMPLE_ICON_SLUGS)) {
  const icon = simpleIcons[key];
  if (!icon) {
    console.warn(`[skip] simple-icons has no export ${key} for ${slug}`);
    continue;
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img"><title>${icon.title}</title><path fill="#${icon.hex}" d="${icon.path}"/></svg>`;
  writeFileSync(path.join(logosDir, `${slug}.svg`), svg, "utf-8");
  brandEntries[slug] = {
    title: icon.title,
    hex: `#${icon.hex}`,
    viewBox: "0 0 24 24",
    kind: "path",
    d: icon.path,
  };
  console.log(`[simple-icons] ${slug} -> #${icon.hex}`);
}

for (const [slug, filename] of Object.entries(DEVICON_SLUGS)) {
  const srcPath = path.join(devCacheDir, filename);
  if (!existsSync(srcPath)) {
    console.warn(`[skip] devicon cache missing for ${slug}: ${srcPath}`);
    continue;
  }
  const raw = readFileSync(srcPath, "utf-8");
  copyFileSync(srcPath, path.join(logosDir, `${slug}.svg`));

  const viewBoxMatch = raw.match(/viewBox="([^"]+)"/);
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();

  brandEntries[slug] = {
    title: slug,
    hex: null,
    viewBox: viewBoxMatch ? viewBoxMatch[1] : "0 0 128 128",
    kind: "markup",
    inner,
  };
  console.log(`[devicon] ${slug} <- ${filename}`);
}

const banner = `/**
 * AUTO-GENERATED by scripts/generate-logos.mjs — do not hand-edit.
 * Regenerate with: node scripts/generate-logos.mjs
 */\n`;

const out = `${banner}
export interface BrandLogoEntry {
  title: string;
  hex: string | null;
  viewBox: string;
  kind: "path" | "markup";
  d?: string;
  inner?: string;
}

export const BRAND_LOGOS: Record<string, BrandLogoEntry> = ${JSON.stringify(
  brandEntries,
  null,
  2
)};
`;

writeFileSync(path.join(root, "src", "lib", "logos.generated.ts"), out, "utf-8");
console.log(`\nWrote src/lib/logos.generated.ts with ${Object.keys(brandEntries).length} brand logos.`);

// Licenses
const siLicenseSrc = path.join(root, "node_modules", "simple-icons", "LICENSE.md");
if (existsSync(siLicenseSrc)) {
  copyFileSync(siLicenseSrc, path.join(logosDir, "LICENSE-simple-icons.md"));
}
const deviconLicenseSrc = path.join(devCacheDir, "devicon-LICENSE");
if (existsSync(deviconLicenseSrc)) {
  copyFileSync(deviconLicenseSrc, path.join(logosDir, "LICENSE-devicon.txt"));
}
console.log("Copied logo licenses into public/logos/.");
